"""Generate KrakenAnimData.cs from the Blender build output. usage: python3 gen_csharp.py OUTDIR CS_PATH"""
import json, sys

out, cs = sys.argv[1], sys.argv[2]
d = json.load(open(f"{out}/kraken_animdata.json"))
e = json.load(open(f"{out}/erupt_data.json"))


def v3(p):
    return f"new Vector3({p[0]}f, {p[1]}f, {p[2]}f)"


def arr_v3(ps):
    return "{ " + ", ".join(v3(p) for p in ps) + " }"


def arr_f(fs):
    return "{ " + ", ".join(f"{x}f" for x in fs) + " }"


L = []
w = L.append
w("// <auto-generated> Generated from the Blender build (gen_csharp.py). Do not edit by hand. </auto-generated>")
w("using System.Collections.Generic;")
w("using UnityEngine;")
w("")
w("namespace MistIsles.Bosses.Kraken")
w("{")
w("    /// <summary>Clip names, lengths, event times and baked geometry probes (kraken local space, scale 1).</summary>")
w("    public static class KrakenAnimData")
w("    {")
for name in d["clips"]:
    w(f'        public const string {name} = "{name}";')
w("")
w("        public static readonly Dictionary<string, float> Length = new Dictionary<string, float>")
w("        {")
for name, c in d["clips"].items():
    w(f'            {{ "{name}", {c["length"]}f }},')
w("        };")
w("")
w("        public static readonly HashSet<string> Looping = new HashSet<string> { " + ", ".join(f'"{n}"' for n, c in d["clips"].items() if c["loop"]) + " };")
w("")
w("        // Event times in seconds (at animator speed 1).")
for name, c in d["clips"].items():
    for ev, t in c["events"].items():
        w(f"        public const float {name.replace('Attack_', '')}_{ev[0].upper() + ev[1:]} = {t}f;")
w("")
p = d["probes"]
w("        // Slam: tentacle segment points at impact (pose at 1.3 s).")
w(f"        public static readonly Vector3[] SlamLImpact = {arr_v3(p['Attack_Slam_L']['impactPoints'])};")
w(f"        public static readonly Vector3[] SlamRImpact = {arr_v3(p['Attack_Slam_R']['impactPoints'])};")
w(f"        public static readonly Vector3[] SweepTipArc = {arr_v3([a['tip'] for a in p['Attack_Sweep']['arc']])};")
w(f"        public static readonly Vector3 GrabPoint = {v3(p['Attack_Grab']['grabPoint'])};")
w(f"        public static readonly Vector3 StunnedWeakPoint = {v3(p['Stunned_Loop']['weakPoint'])};")
w("")
r = d["tentacleRadii"]
w(f"        public static readonly float[] FrontTentacleRadii = {arr_f(r['FL'])};")
w(f"        public static readonly float[] EruptTentacleRadii = {arr_f(e['radii'])};")
w(f"        public const float EruptLength = {e['length']}f;")
w(f"        public const float Erupt_HitStart = {e['events']['hitStart']}f;")
w(f"        public const float Erupt_HitEnd = {e['events']['hitEnd']}f;")
w(f"        public const float Erupt_Length = {e['clips']['Erupt']}f;")
w("")
rest = d["rest"]
w("        // Rest (bind) pose helpers used by the setup tool to place colliders.")
w(f"        public static readonly Vector3 WeakPointCenterRest = {v3(rest['weakPointCenter'])};")
w(f"        public const float WeakPointRadius = {rest['weakPointRadius']}f;")
w(f"        public static readonly Vector3[] BodyAxisRest = {arr_v3(rest['bodyAxis'])};")
w(f"        public static readonly float[] BodyRadii = {arr_f(rest['bodyRadii'])};")
w("")
w("        public static float GetLength(string clip)")
w("        {")
w("            return Length.TryGetValue(clip, out var l) ? l : 1f;")
w("        }")
w("    }")
w("}")
open(cs, "w").write("\n".join(L) + "\n")
print("wrote", cs)
